#!/usr/bin/env python3
"""Render measured paper statements from checked-in JSON artifacts.

Only reads experiment records. It never runs an experiment, silently fills a
missing measured number, or treats a missing validation artifact as a pass.
Each input is hashed in generated/input_manifest.json for table provenance.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from fractions import Fraction
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUT = Path(__file__).resolve().parent / "generated"
MANIFEST: list[dict[str, str]] = []


def read(path: Path) -> dict:
    raw = path.read_bytes()
    MANIFEST.append({"path": path.relative_to(ROOT).as_posix(),
                     "sha256": hashlib.sha256(raw).hexdigest()})
    return json.loads(raw)


def tex(text: str) -> str:
    replacements = {"\\": r"\textbackslash{}", "_": r"\_", "&": r"\&",
                    "%": r"\%", "#": r"\#", "$": r"\$", "{": r"\{",
                    "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    return "".join(replacements.get(char, char) for char in str(text))


def write_content(path: Path, contents: str) -> None:
    if not path.exists() or path.read_text() != contents:
        path.write_text(contents)


def write(name: str, contents: str) -> None:
    OUT.mkdir(exist_ok=True)
    write_content(OUT / name, "% Generated by render_results.py; do not hand-edit.\n" + contents + "\n")


def table(caption: str, label: str, columns: str, head: str, rows: list[str]) -> str:
    return "\n".join([r"\begin{table}[t]", r"\centering", r"\small",
                       r"\caption{" + caption + "}", r"\label{" + label + "}",
                       r"\begin{tabular}{" + columns + "}", r"\toprule", head,
                       r"\midrule", *rows, r"\bottomrule", r"\end{tabular}", r"\end{table}"])


def synthetic(data: dict) -> None:
    methods = ("v1-independent-flat", "v2-centered-divided-tree", "v2-direct-residual-tree")
    balanced = [r for r in data["attention"] if r["case"] == "balanced-nonconstant"]
    lengths = sorted({r["entries"] for r in balanced})
    rows = []
    for length in lengths:
        values = []
        for method in methods:
            matches = [r for r in balanced if r["entries"] == length and r["method"] == method]
            if len(matches) != 1 or matches[0]["equal_e24_dense"] is not True:
                raise ValueError("Missing, duplicate, or failed paired comparison")
            row = matches[0]
            values.append(f'{row["raw_entries_read"]}/{row["summary_records_read"]}')
        rows.append(f"{length:,} & " + " & ".join(values) + r" \\")
    write("attention_table.tex", table(
        "Balanced fixture: raw rows / summary records read per query. All three methods agree with dense E24. Initial indexing is additional work.",
        "tab:reads", "rccc", r"Rows & Indep. flat & Centered ratio & Direct \\", rows))
    trajectories = data["state_trajectories"]
    if not all(r["all_tokens_and_states_equal"] is True for r in trajectories):
        raise ValueError("State comparison failed; revise the manuscript")
    rows = []
    writes = [r for r in trajectories if r["strategy"] == "writes"]
    for strategy in ("cuts", "writes"):
        rs = [r for r in trajectories if r["strategy"] == strategy]
        if not rs:
            raise ValueError(f"No trajectory data for {strategy}")
        steps = sum(r["steps"] for r in rs)
        raw = sum(r["raw_rows_all_layers_steps"] for r in rs)
        accepted = str(sum(r["write_frontier_accepts"] for r in rs)) if strategy == "writes" else "---"
        rows.append(f"{strategy.title()} & {steps} & {raw:,} & {accepted}" + r" \\")
    write("state_table.tex", table(
        "Complete-state toy-decoder comparisons. Raw reads sum over layers and steps; write acceptance applies only to the writes strategy. Every compared token and full state agrees.",
        "tab:state", "lrrr", r"Strategy & Steps & Raw rows & Write accepts \\", rows))
    write("macros.tex", "\n".join([
        r"\newcommand{\WriteAccepts}{" + str(sum(r["write_frontier_accepts"] for r in writes)) + "}",
        r"\newcommand{\WriteSteps}{" + str(sum(r["steps"] for r in writes)) + "}"]))


def runtime(directory: Path) -> None:
    parts = []
    arithmetic = directory / "device_arithmetic.json"
    if arithmetic.exists():
        data = read(arithmetic)
        if data["device_executed"] is not True:
            raise ValueError("Device arithmetic record does not assert execution")
        parts.append(
            f"The GH200 device arithmetic oracle check passed {data['passed']:,} comparisons: "
            f"{data['moment_cases']:,} moment cases, {data['all_finite_canonical_bf16_cells']:,} "
            f"finite canonical BF16 cells, {data['e24_weight_cases']:,} E24 weight cases, "
            f"{data['e24_grid_rounding_cases']} lattice-rounding cases, and "
            f"{data['exact_negative_tail_cases']} negative-tail cases. "
            "These are executed finite comparisons, not a formal proof of device arithmetic. "
            "The CUDA checker uses the chord envelope; the finite-count refinement is used by the rational CPU reference.")
        if sum(data[name] for name in ("moment_cases", "all_finite_canonical_bf16_cells", "e24_weight_cases",
                                      "e24_grid_rounding_cases", "exact_negative_tail_cases")) != data["passed"]:
            raise ValueError("Arithmetic case counts do not sum to the reported total")
    else:
        parts.append("No device arithmetic result is present in the selected run directory.")
    micro = directory / "microbenchmark_h8_n32768_d64.json"
    if micro.exists():
        data = read(micro)
        if data["backend_equivalence_proved"] is not False or data["end_to_end_speedup"] is not None:
            raise ValueError("Unexpected microbenchmark contract; review before publication")
        device = data["gate"]["device_ms"]
        graph = data["gate"]["graph_amortized_device_ms"]
        sdpa = data["torch_sdpa"]["graph_amortized_device_ms"]
        parts.append(
            "On " + tex(data["gpu"]) + " (compute capability " + ".".join(map(str, data["compute_capability"])) + "), "
            f"a synthetic {data['heads']}-head, {data['length']:,}-row, {data['dim']}-coordinate "
            f"root gate has a {1000*device['p50']:.2f}~$\\mu$s median single-call event span "
            f"({1000*device['p95']:.2f}~$\\mu$s empirical 95th percentile), including host submission gaps. "
            f"Graph batches of {data['graph_batch']} sequential fixed-input calls give "
            f"{1000*graph['p50']:.2f}~$\\mu$s median per call "
            f"({1000*graph['p95']:.2f}~$\\mu$s 95th percentile); "
            f"the separate SDPA primitive gives {1000*sdpa['p50']:.2f}~$\\mu$s in that graph protocol. "
            f"Recorded construction took {data['construction_ms']:.2f}~ms. "
            "The proposal was the construction's known value 16, and the accepted gate read zero raw KV rows. "
            "Torch " + tex(data["torch"]) + " and CUDA " + tex(data["cuda"]) + " were used. "
            "Graph amortization is not token latency. The two primitives have different numerical contracts; "
            "construction, refinement, and a decoder suffix are excluded from their event spans.")
    captures = sorted(directory.glob("pretrained_*.json"))
    capture_rows = []
    for path in captures:
        data = read(path)
        if "workloads" not in data or "model" not in data:
            continue
        workloads = data["workloads"]
        if data.get("backend_replacement_authorized") is not False:
            raise ValueError("Pretrained record has an unexpected replacement scope")
        if not all(r["all_layer_kv_bit_equal"] is True and r["last_position_logits_equal"] is True
                   for r in workloads):
            raise ValueError("Observer transparency failed; revise measured claim")
        name = data["model"].split("/")[-1]
        steps = sum(r["decode_steps"] for r in workloads)
        states = sum(r["states_compared"] for r in workloads)
        events = sum(r["captures"] for r in workloads)
        capture_rows.append(f"{tex(name)} & {len(workloads)} & {steps} & {states} & {events}" + r" \\")
    if capture_rows:
        parts.append(table(
            "Pretrained observer transparency, compared to the unchanged backend. State comparisons include prefill and every decode step; events are captured decode attention calls. This does not run a filtered replacement.",
            "tab:pretrained", "lrrrr", r"Model & Cases & Steps & States & Events \\", capture_rows))
        parts.append("The observer study uses pinned checkpoint revisions, three deterministic prompt constructions at contexts 128 and 512, and three decode steps per case. "
                     "All recorded per-layer KV tensors agree bitwise and final-position logits agree in value with the unobserved run. "
                     "It tests capture transparency; it does not test StateCut as a model replacement. Checkpoint hashes and exact prompt token IDs are retained in the source records.")
    else:
        parts.append("No completed pretrained observer result is present in the selected run directory.")
    write("runtime_evidence.tex", "\n\n".join(parts))


def fraction_tex(value: str) -> str:
    number = Fraction(value)
    if number.denominator == 1:
        return str(number.numerator)
    sign = "-" if number < 0 else ""
    return sign + r"\frac{" + str(abs(number.numerator)) + "}{" + str(number.denominator) + "}"


def integer(directory: Path) -> None:
    path = directory / "integer_moment.json"
    if not path.exists():
        write("integer_result.tex", "No finite-count audit record is present in the selected run directory.")
        return
    data = read(path)
    example = data["strict_three_row"]
    grid = data["integer_moment_exhaustive"]
    if (example["both_equal_e24_dense"] is not True
            or example["continuous_chord"]["accepted"] is not False
            or example["integer_count"]["accepted"] is not True
            or grid["both_residual_extremes_match"] is not True):
        raise ValueError("Finite-count audit changed; revise manuscript interpretation")
    before = example["lower_boundary"]["continuous_chord"][0]
    after = example["lower_boundary"]["integer_count"][0]
    write("integer_result.tex", "\n".join([
        "The recorded lower-bound residuals at the left cell boundary are",
        r"\begin{equation}",
        r"\underline R_{\rm ch}=" + fraction_tex(before) + r"<0,\quad "
        + r"\underline R_{\rm int}=" + fraction_tex(after) + ">0.",
        r"\end{equation}",
        f"Both methods return the dense result {tex(example['expected_bf16'][0])}; "
        f"the chord method reads {example['continuous_chord']['reads']['raw_entries']} raw rows "
        f"and the integer method reads {example['integer_count']['reads']['raw_entries']}. "
        f"An exhaustive finite-grid audit checks {grid['row_multisets']:,} row multisets, "
        f"{grid['row_threshold_evaluations']:,} row/threshold combinations, and "
        f"{grid['fixed_sum_threshold_optima']:,} fixed-sum/threshold optima against both attained residual extremes. "
        "It uses counts 1--6 and the nine-point grid from $-1$ to $1$ in increments of $1/4$; "
        "these finite tests support the implementation, while the general bound is proved mathematically."
    ]))
    ablation = data["ablation"]
    if not all(row["both_equal_e24_dense"] is True for row in ablation):
        raise ValueError("Finite-count ablation contains a mismatched output")
    points = {}
    for row in ablation:
        points[(row["rows"], Fraction(row["score_magnitude"]))] = row
    csv = ["rows,chord,integer013,integer015"]
    for n in sorted({row["rows"] for row in ablation}):
        a, b = points[(n, Fraction(13, 100))], points[(n, Fraction(3, 20))]
        old_a = 100 * Fraction(a["continuous_chord"]["reads"]["raw_entries"], n)
        old_b = 100 * Fraction(b["continuous_chord"]["reads"]["raw_entries"], n)
        if old_a != old_b:
            raise ValueError("Ablation chord curves differ; revise the plot")
        vals = [old_a, 100 * Fraction(a["integer_count"]["reads"]["raw_entries"], n),
                100 * Fraction(b["integer_count"]["reads"]["raw_entries"], n)]
        csv.append(str(n) + "," + ",".join(str(float(v)) for v in vals))
    write_content(OUT / "integer_ablation.csv", "\n".join(csv) + "\n")


def formal(directory: Path) -> None:
    path = directory / "formal/summary.json"
    if not path.exists():
        write("formal_evidence.tex", "No successful formal-build audit is present in the selected run directory.")
        write("formal_inventory.tex", "No compiled theorem inventory is available.")
        return
    data = read(path)
    if data["build_passed"] is not True or data["unexpected_dependencies"]:
        raise ValueError("Formal audit did not pass")
    standard = {"Classical.choice", "Quot.sound", "propext"}
    if set(data["allowed_axioms"]) != standard:
        raise ValueError("Formal foundational assumptions changed; review manuscript")
    source_theorems = data["source_theorems"]
    if len(source_theorems) != data["source_theorem_count"]:
        raise ValueError("Inconsistent formal theorem count")
    for name, digest in data["source_sha256"].items():
        if hashlib.sha256((ROOT / name).read_bytes()).hexdigest() != digest:
            raise ValueError("Formal evidence is stale for " + name)
    write("formal_evidence.tex", "\n".join([
        f"The pinned Lean build succeeds and audits {data['source_theorem_count']} source theorems "
        f"({data['audited_theorem_count']} compiled theorem constants including generated helpers). "
        "Only the standard foundational axioms "
        r"\code{propext}, \code{Classical.choice}, and \code{Quot.sound} occur. "
        "The compiled results cover chord and finite-count residual bounds, finite-count attainment "
        "and chord dominance, a mathematical floor/remainder contract, open/closed cell gates, "
        "disjoint-sum composition, singleton writes, and future traces. "
        r"\Cref{app:formal} maps the claims to actual compiled declaration names. "
        "The proof does not establish a Python/CUDA refinement or instantiate a deployed-backend error bound."
    ]))
    groups = [
        ("Moment and residual bounds", ["abs_chord_sum", "moment_residual_sound", "finite_abs_sum_bound", "finite_residual_bound"]),
        ("Finite-count strength and feasibility", ["finite_envelope_le_chord", "finite_envelope_attained", "floor_remainder_contract"]),
        ("Rounding-cell composition", ["residual_to_cell", "moment_to_cell", "finite_to_cell"]),
        ("Conditional numerical bridge", ["backend_bridge_gate", "backend_bridge_cell"]),
        ("Disjoint frontier sums", ["disjoint_split_sum", "frontier_sum_bounds"]),
        ("Persistent writes and traces", ["singleton_writes", "checked_write_frontier", "write_frontier_future"]),
    ]
    rows = []
    for title, names in groups:
        present = [r"\code{" + tex(name) + "}" for name in names if "StateCut." + name in source_theorems]
        if not present:
            raise ValueError("Missing expected theorem family: " + title)
        rows.append(title + " & " + ", ".join(present) + r" \\")
    text = [
        "The build uses " + r"\code{" + tex(data["toolchain"]) + "}, with Mathlib at "
        + r"\nolinkurl{" + data["mathlib_revision"] + "}. "
        "The audit counts source theorem declarations separately from generated logical helpers. "
        f"It records {len(data['compiler_runtime_auxiliaries_outside_proof_audit'])} compiler runtime extraction "
        "auxiliaries outside the proof inventory; these are not used to replace kernel checking. "
        "The reported counts and names come from the build audit JSON.",
        r"\begin{center}", r"\begin{tabular}{p{0.29\textwidth}p{0.65\textwidth}}",
        r"\toprule", r"Claim family & Compiled declarations in namespace \code{StateCut} \\",
        r"\midrule", *rows, r"\bottomrule", r"\end{tabular}", r"\end{center}",
        "The finite-count theorem takes an integer endpoint count and a remainder satisfying the "
        "summary equation. The separate mathematical floor/remainder theorem supplies those "
        "conditions in the nonconstant, non-upper-endpoint case. Constant cases are proved separately. "
        "Neither result establishes that Python's runtime executes the specified mathematics; "
        "the exact-rational tests check that implementation separately. "
        "The cell theorems take a correct rounding-cell contract as a premise and do not prove "
        "the full BF16 encoding/cell generator. The frontier results concern disjoint sums; "
        "they do not formally verify the Python persistent forest or its memory-access counters."
    ]
    write("formal_inventory.tex", "\n\n".join(text))


def cuda_acceptance(directory: Path) -> None:
    def load_aggregates(path: Path, classified: bool) -> dict:
        data = read(path)
        if data["backend_replacement_authorized"] is not False or data["performance_claim"] is not None:
            raise ValueError("Unexpected CUDA capture-audit contract")
        grouped = {}
        fields = ["heads", "accepted_heads", "calls", "accepted_calls"]
        if classified:
            fields += ["invalid_weight_heads", "nonpositive_mass_heads", "valid_mass_heads"]
        for row in data["aggregates"]:
            key = row["block_size"], row["proposal"]
            bucket = grouped.setdefault(key, dict.fromkeys(fields, 0))
            for name in bucket:
                bucket[name] += row[name]
        if classified:
            for row in grouped.values():
                if row["heads"] != row["invalid_weight_heads"] + row["nonpositive_mass_heads"] + row["valid_mass_heads"]:
                    raise ValueError("CUDA denominator/domain classification is incomplete")
        return grouped

    path = directory / "capture_cuda_audit.json"
    if not path.exists():
        write("cuda_acceptance.tex", "No completed pretrained CUDA-gate acceptance audit is available.")
        write("cuda_domains.tex", "No completed CUDA domain classification is available.")
        return
    grouped = load_aggregates(path, True)
    previous = load_aggregates(directory / "capture_cuda_audit_half_quantum.json", False)
    baseline = grouped[(1, "observed_sdpa_oracle")]
    old = previous[(1, "observed_sdpa_oracle")]
    rows, domain_rows = [], []
    for size in sorted({key[0] for key in grouped}):
        mean, oracle = [grouped[(size, method)] for method in ("summary_uniform_mean", "observed_sdpa_oracle")]
        if mean["heads"] != oracle["heads"] or mean["calls"] != oracle["calls"]:
            raise ValueError("Unpaired proposal populations in CUDA audit")
        prior = previous[(size, "observed_sdpa_oracle")]
        if prior["heads"] != oracle["heads"] or prior["calls"] != oracle["calls"]:
            raise ValueError("Unpaired enclosure populations in CUDA audit")
        for field in ("invalid_weight_heads", "nonpositive_mass_heads", "valid_mass_heads"):
            if mean[field] != oracle[field]:
                raise ValueError("Proposal-dependent domain population; revise domain table")
        rows.append(f"{size} & {mean['accepted_heads']:,} & {prior['accepted_heads']:,} & "
                    f"{oracle['accepted_heads']:,} & {mean['accepted_calls']}/{oracle['accepted_calls']}" + r" \\")
        domain_rows.append(f"{size} & {oracle['invalid_weight_heads']:,} & "
                           f"{oracle['nonpositive_mass_heads']:,} & {oracle['valid_mass_heads']:,}" + r" \\")
    if any(row["accepted_calls"] for row in grouped.values()):
        raise ValueError("Complete-call acceptance changed; revise negative-result interpretation")
    contents = [
        r"\paragraph{Pretrained local-gate acceptance.}",
        f"The CUDA audit evaluates {baseline['calls']:,} captured attention calls "
        f"and {baseline['heads']:,} query heads per configuration across both checkpoints. "
        "It compares a summary-mean proposal with the already observed SDPA output as a diagnostic oracle proposal. "
        "The oracle's dense computation is additional work, and its output need not equal E24.",
        table(
            f"Pretrained CUDA acceptance: {baseline['heads']:,} heads and {baseline['calls']:,} calls per configuration. "
            "Mean uses the lattice enclosure. Oracle columns compare the half-quantum (HQ) and lattice (L) weight enclosures. "
            "The last column counts complete calls for mean/oracle with L.",
            "tab:cudaacceptance", "rcccc",
            r"Block & Mean & Oracle HQ & Oracle L & Calls \\", rows),
        "Monotone rounding of outward exponential endpoints onto the E24 lattice "
        r"tightens the half-quantum enclosure (\cref{app:lattice}) and changes block-1 oracle acceptance "
        f"from {old['accepted_heads']:,} to {baseline['accepted_heads']:,} heads. "
        "No complete all-head call passes. Block size 1 reads one summary per row, "
        "so its local certificates supply no sublinear summary-read advantage. "
        r"Domain rejection and failure to prove positive mass are counted separately in \cref{app:domains}. "
        "These fixed workloads provide negative evidence for the current coarse summaries, not a population acceptance estimate."
    ]
    write("cuda_acceptance.tex", "\n\n".join(contents))
    write("cuda_domains.tex", "\n".join([
        r"\begin{center}", r"\begin{tabular}{rrrr}", r"\toprule",
        r"Block size & Unsupported weights & Positive mass unproved & Valid positive mass \\",
        r"\midrule", *domain_rows, r"\bottomrule", r"\end{tabular}", r"\end{center}",
        "The columns partition the query heads within each configuration. "
        "Unsupported weight enclosures are rejected before the output predicate; "
        "a nonpositive lower denominator bound does not establish that the actual denominator is nonpositive. "
        "The two proposal methods share these counts. Accepted-head counts use the full population, "
        "including rejected domains, rather than silently excluding unsupported cases. "
        "CUDA admits a narrower positive-score domain than the rational oracle. "
        "The capture audit requires the exact query scale $1/8$, as used by these head-dimension-64 models; "
        "arbitrary rounded query scaling is outside this audit's contract."
    ]))


def e24_captures(directory: Path) -> None:
    path = directory / "e24/summary.json"
    if not path.exists():
        write("e24_captures.tex", "No completed exact-E24 pretrained audit is available.")
        return
    data = read(path)
    if (data["backend_replacement_authorized"] is not False
            or data["all_e24_equal_dense"] is not True or data["unsupported_heads"] != 0
            or data["accepted_without_fallback"] != 0):
        raise ValueError("Exact-E24 subset scope or result changed; revise manuscript")
    heads = [head for row in data["rows"] for head in row["heads"]]
    if len(heads) != data["heads_tested"] or not all(head["e24_equal_dense"] is True for head in heads):
        raise ValueError("Exact-E24 head records do not support aggregate")
    if any(head["raw_entries"] != head["entries"] for head in heads):
        raise ValueError("Exact-E24 raw fallback count changed")
    if sum(head["coordinates"] for head in heads) != data["coordinates"]:
        raise ValueError("Exact-E24 coordinate count mismatch")
    if sum(head["observed_backend_bit_matches"] for head in heads) != data["observed_backend_bit_matches"]:
        raise ValueError("Backend bit-match count mismatch")
    scores = read(directory / "algorithm/qwen_code_128_layer0_score_domain.json")
    extreme = max(scores["rows"], key=lambda row: Fraction(row["max"]))
    extension = read(directory / "algorithm/extended_e24_tests.json")
    if extension["failed"] != 0 or "2048" not in extension["scores"]:
        raise ValueError("Extended exponential guard lacks the recorded check")
    differences = data["coordinates"] - data["observed_backend_bit_matches"]
    write("e24_captures.tex", "\n".join([
        r"\paragraph{Exact reference on captured heads.}",
        f"A deterministic subset evaluates {data['heads_tested']} query heads "
        f"({data['coordinates']:,} coordinates): the first two heads in the first, middle, and last layer "
        "at the first decode step for each model/prompt/context case. "
        "The finite-count CPU filter agrees with dense E24 on every tested head, "
        "using all raw rows through fallback in every case. "
        f"E24 matches the observed SDPA bits on {data['observed_backend_bit_matches']:,} coordinates "
        f"and differs on {differences:,}. "
        "This comparison uses E24's canonical zero and the unmodified observed bits. "
        "The measured disagreement rules out treating these numerical profiles as interchangeable. "
        f"One Qwen head has actual positive scores from {float(Fraction(extreme['min'])):,.3f} "
        f"to {float(Fraction(extreme['max'])):,.3f}; extending the rigorous CPU "
        "exponential oracle to 2,048 with magnitude-aware precision supports the tested cases. "
        "No common score shift is applied."
    ]))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--experiment", type=Path, default=ROOT / "results/gh200/algorithm/v2_experiments.json")
    parser.add_argument("--run-directory", type=Path, default=ROOT / "results/gh200")
    args = parser.parse_args()
    required = [args.experiment, *[args.run_directory / name for name in (
        "device_arithmetic.json", "microbenchmark_h8_n32768_d64.json", "integer_moment.json",
        "formal/summary.json", "pretrained_smollm2-135m.json", "pretrained_qwen2.5-0.5b.json",
        "capture_cuda_audit.json", "capture_cuda_audit_half_quantum.json", "e24/summary.json",
        "algorithm/qwen_code_128_layer0_score_domain.json", "algorithm/extended_e24_tests.json")]]
    missing = [str(path) for path in required if not path.is_file()]
    if missing:
        raise FileNotFoundError("Required manuscript evidence is missing: " + ", ".join(missing))
    synthetic(read(args.experiment.resolve()))
    runtime(args.run_directory.resolve())
    integer(args.run_directory.resolve())
    formal(args.run_directory.resolve())
    cuda_acceptance(args.run_directory.resolve())
    e24_captures(args.run_directory.resolve())
    write_content(OUT / "input_manifest.json", json.dumps({
        "generator": "paper/render_results.py", "inputs": MANIFEST,
        "scope": "JSON-to-LaTeX rendering only; measurements require their original experiment checks"
    }, indent=2) + "\n")


if __name__ == "__main__":
    main()
